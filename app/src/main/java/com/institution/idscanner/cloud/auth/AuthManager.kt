package com.institution.idscanner.cloud.auth

import android.content.Context
import android.content.Intent
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInAccount
import com.google.android.gms.auth.api.signin.GoogleSignInClient
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.common.api.ApiException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await

/**
 * Google sign-in via the classic GoogleSignInClient API (NOT Credential
 * Manager, for reliability on older devices). The Firebase UID of the
 * signed-in Google account is the User ID: all cloud data is scoped to it.
 *
 * The OAuth web client ID comes from the `default_web_client_id` string
 * resource generated by the Google services plugin from the real
 * google-services.json. If that resource is missing (placeholder build),
 * sign-in fails gracefully with a Bengali error instead of crashing.
 */
class AuthManager(private val context: Context) {

    private val auth: FirebaseAuth = FirebaseAuth.getInstance()

    private val _currentUser = MutableStateFlow<FirebaseUser?>(auth.currentUser)
    val currentUser: StateFlow<FirebaseUser?> = _currentUser.asStateFlow()

    val uid: String? get() = auth.currentUser?.uid
    val email: String? get() = auth.currentUser?.email

    init {
        auth.addAuthStateListener { _currentUser.value = it.currentUser }
    }

    private fun googleClient(): GoogleSignInClient? {
        val webClientId = try {
            val resId = context.resources.getIdentifier(
                "default_web_client_id", "string", context.packageName
            )
            if (resId == 0) null else context.getString(resId)
        } catch (_: Exception) {
            null
        } ?: return null
        val gso = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestIdToken(webClientId)
            .requestEmail()
            .build()
        return GoogleSignIn.getClient(context, gso)
    }

    /** Intent to launch for Google sign-in, or null if not configured. */
    fun signInIntent(): Intent? = googleClient()?.signInIntent

    /** Completes sign-in from the activity result. Returns an error message, or null on success. */
    suspend fun handleSignInResult(data: Intent?): String? {
        return try {
            val task = GoogleSignIn.getSignedInAccountFromIntent(data)
            val account: GoogleSignInAccount = task.getResult(ApiException::class.java)
            val idToken = account.idToken
                ?: return "Google লগইন থেকে টোকেন পাওয়া যায়নি। আবার চেষ্টা করুন।"
            val credential = GoogleAuthProvider.getCredential(idToken, null)
            auth.signInWithCredential(credential).await()
            _currentUser.value = auth.currentUser
            null
        } catch (e: ApiException) {
            "Google লগইন বাতিল হয়েছে বা ব্যর্থ হয়েছে। (কোড: ${e.statusCode})"
        } catch (e: Exception) {
            "লগইন ব্যর্থ: ${e.message ?: "অজানা ত্রুটি"}"
        }
    }

    /** True when the Google services config is present in this build. */
    fun isConfigured(): Boolean = googleClient() != null

    suspend fun signOut() {
        try {
            googleClient()?.signOut()?.await()
        } catch (_: Exception) {
        }
        auth.signOut()
        _currentUser.value = null
    }
}
